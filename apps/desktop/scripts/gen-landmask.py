def inside(poly, x, y):
    """Even-odd ray cast."""
    c = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            c = not c
        j = i
    return c


def is_land(x, y):
    hits = sum(1 for p in POLYS.values() if inside(p, x, y))
    return hits % 2 == 1


def main():
    rows = []
    sub = 4
    for r in range(ROWS):
        bits = []
        for c in range(COLS):
            n = 0
            for sy in range(sub):
                for sx in range(sub):
                    lon = -180 + (c + (sx + 0.5) / sub) * CELL
                    lat = 90 - (r + (sy + 0.5) / sub) * CELL
                    n += is_land(lon, lat)
            bits.append("1" if n >= 4 else "0")
        word = "".join(bits)
        rows.append("".join(f"{int(word[i:i + 4], 2):x}" for i in range(0, COLS, 4)))

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "lib", "landmask.ts")
