//! Point the operating system resolver at the DNS vault
//! (`DNS_VAULT_V4` / `DNS_VAULT_V6`) and restore the originals on disarm.
//!
//! The originals are saved to `<state_dir>/dns-backup.json` *before* anything
//! is changed, so a restore still works after a daemon crash or reboot.
//!
//! * macOS: `networksetup -getdnsservers / -setdnsservers` for every enabled
//!   service from `networksetup -listallnetworkservices`.
//! * Windows: `netsh interface ipv4|ipv6 set dnsservers` on the tunnel
//!   interface, and the tunnel interface gets the lowest metric.
//! * Linux: `resolvectl` on the tunnel link when systemd-resolved runs, else a
//!   backed-up `/etc/resolv.conf`.

use std::net::IpAddr;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use vw_core::consts::{DNS_VAULT_V4, DNS_VAULT_V6};
use vw_core::Result;

use crate::plan::TunnelIface;

/// The two vault resolver addresses.
pub fn vault_servers() -> [IpAddr; 2] {
    [IpAddr::V4(DNS_VAULT_V4), IpAddr::V6(DNS_VAULT_V6)]
}

/// What was there before VoidWire changed it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum DnsBackup {
    /// macOS: per network service, the configured servers (empty = DHCP / "Empty").
    MacOs {
        services: Vec<(String, Vec<String>)>,
    },
    /// Windows: static servers were set on this interface alias.
    Windows { iface: String },
    /// Linux with systemd-resolved: per-link DNS set on this interface.
    Resolved { iface: String },
    /// Linux without resolved: previous `/etc/resolv.conf` contents or link.
    ResolvConf {
        content: Option<String>,
        symlink: Option<PathBuf>,
    },
}

/// `networksetup -listallnetworkservices` → enabled service names.
pub fn parse_network_services(out: &str) -> Vec<String> {
    out.lines()
        .skip_while(|l| l.starts_with("An asterisk"))
        .map(str::trim_end)
        .filter(|l| !l.is_empty() && !l.starts_with('*') && !l.starts_with("An asterisk"))
        .map(str::to_string)
        .collect()
}

/// `networksetup -getdnsservers <svc>` → configured servers (may be empty).
pub fn parse_dns_servers(out: &str) -> Vec<String> {
    out.lines()
        .map(str::trim)
        .filter(|l| l.parse::<IpAddr>().is_ok())
        .map(str::to_string)
        .collect()
}

/// `/etc/resolv.conf` pointing at the vault.
pub fn render_resolv_conf() -> String {
    format!(
        "# Generated by VoidWire (voidwired); restored on disarm.\nnameserver {DNS_VAULT_V4}\nnameserver {DNS_VAULT_V6}\noptions edns0 trust-ad\n"
    )
}

/// `networksetup -setdnsservers` arguments for one service.
pub fn macos_set_args(service: &str, servers: &[String]) -> Vec<String> {
    let mut v = vec!["-setdnsservers".to_string(), service.to_string()];
    if servers.is_empty() {
        v.push("Empty".into());
    } else {
        v.extend(servers.iter().cloned());
    }
    v
}

/// `netsh` argument lists that pin the vault on a Windows interface.
pub fn windows_set_args(iface: &str) -> Vec<Vec<String>> {
    let name = format!("name={iface}");
    vec![
        [
            "interface",
            "ipv4",
            "set",
            "dnsservers",
            &name,
            "source=static",
            &format!("address={DNS_VAULT_V4}"),
            "register=none",
            "validate=no",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect(),
        [
            "interface",
            "ipv6",
            "set",
            "dnsservers",
            &name,
            "source=static",
            &format!("address={DNS_VAULT_V6}"),
            "register=none",
            "validate=no",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect(),
    ]
}

/// System DNS controller.
#[derive(Debug)]
pub struct SystemDns {
    backup_path: PathBuf,
    backup: Option<DnsBackup>,
}

impl SystemDns {
    /// Loads a backup left by a previous run so `restore` works after a crash.
    pub fn new(state_dir: &Path) -> Self {
        let backup_path = state_dir.join("dns-backup.json");
        let backup = std::fs::read(&backup_path)
            .ok()
            .and_then(|b| serde_json::from_slice(&b).ok());
        Self {
            backup_path,
            backup,
        }
    }

    pub fn is_applied(&self) -> bool {
        self.backup.is_some()
    }

    pub fn backup(&self) -> Option<&DnsBackup> {
        self.backup.as_ref()
    }

    fn save(&mut self, b: DnsBackup) -> Result<()> {
        // Never overwrite the originals with our own vault settings.
        if self.backup.is_none() {
            let json = serde_json::to_vec_pretty(&b)?;
            crate::cmd::write_atomic(&self.backup_path, &json)?;
            self.backup = Some(b);
        }
        Ok(())
    }

    fn clear(&mut self) -> Result<()> {
        self.backup = None;
        match std::fs::remove_file(&self.backup_path) {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(e.into()),
        }
    }

    /// Point the system resolver at the vault. Idempotent.
    pub fn apply(&mut self, tunnel: Option<&TunnelIface>) -> Result<()> {
        if let Some(t) = tunnel {
            crate::plan::validate_ifname(&t.name)?;
        }
        self.apply_os(tunnel)
    }

    #[cfg(target_os = "macos")]
    fn apply_os(&mut self, _tunnel: Option<&TunnelIface>) -> Result<()> {
        const NS: &str = "/usr/sbin/networksetup";
        let list = crate::cmd::run_ok(NS, &["-listallnetworkservices"], None)?;
        let services = parse_network_services(&list.stdout);
        if self.backup.is_none() {
            let mut saved = Vec::new();
            for svc in &services {
                let out = crate::cmd::run_ok(NS, &["-getdnsservers", svc], None)?;
                saved.push((svc.clone(), parse_dns_servers(&out.stdout)));
            }
            self.save(DnsBackup::MacOs { services: saved })?;
        }
        let vault: Vec<String> = vault_servers().iter().map(ToString::to_string).collect();
        for svc in &services {
            let a = macos_set_args(svc, &vault);
            let a: Vec<&str> = a.iter().map(String::as_str).collect();
            crate::cmd::run_ok(NS, &a, None)?;
        }
        tracing::debug!(services = services.len(), "system DNS pointed at vault");
        Ok(())
    }

    #[cfg(target_os = "windows")]
    fn apply_os(&mut self, tunnel: Option<&TunnelIface>) -> Result<()> {
        let t = tunnel.ok_or_else(|| {
            vw_core::VwError::Dns(
                "Windows DNS is set on the tunnel interface, which does not exist yet".into(),
            )
        })?;
        self.save(DnsBackup::Windows {
            iface: t.name.clone(),
        })?;
        for a in windows_set_args(&t.name) {
            let a: Vec<&str> = a.iter().map(String::as_str).collect();
            crate::cmd::run_ok("netsh", &a, None)?;
        }
        if let Some(luid) = t.luid {
            crate::windows::routes::set_interface_metric(luid, false, 1)?;
            if t.v6.is_some() {
                crate::windows::routes::set_interface_metric(luid, true, 1)?;
            }
        } else {
            let iface = format!("interface={}", t.name);
            crate::cmd::run_ok(
                "netsh",
                &["interface", "ipv4", "set", "interface", &iface, "metric=1"],
                None,
            )?;
        }
        Ok(())
    }

    #[cfg(target_os = "linux")]
    fn apply_os(&mut self, tunnel: Option<&TunnelIface>) -> Result<()> {
        let resolvectl =
            crate::cmd::resolve("resolvectl", &["/usr/bin/resolvectl", "/bin/resolvectl"]);
        let resolved_up = crate::cmd::run(&resolvectl, &["status"], None)
            .map(|o| o.success)
            .unwrap_or(false);
        let use_resolved = match &self.backup {
            Some(DnsBackup::Resolved { .. }) => true,
            Some(_) => false,
            None => resolved_up && tunnel.is_some(),
        };
        if use_resolved {
            let t =
                tunnel.ok_or_else(|| vw_core::VwError::Dns("tunnel interface missing".into()))?;
            self.save(DnsBackup::Resolved {
                iface: t.name.clone(),
            })?;
            let v4 = DNS_VAULT_V4.to_string();
            let v6 = DNS_VAULT_V6.to_string();
            crate::cmd::run_ok(&resolvectl, &["dns", &t.name, &v4, &v6], None)?;
            crate::cmd::run_ok(&resolvectl, &["domain", &t.name, "~."], None)?;
            crate::cmd::run_ok(&resolvectl, &["default-route", &t.name, "true"], None)?;
            return Ok(());
        }
        let path = Path::new("/etc/resolv.conf");
        if self.backup.is_none() {
            let symlink = std::fs::read_link(path).ok();
            let content = if symlink.is_some() {
                None
            } else {
                std::fs::read_to_string(path).ok()
            };
            self.save(DnsBackup::ResolvConf { content, symlink })?;
        }
        if std::fs::symlink_metadata(path).is_ok_and(|m| m.file_type().is_symlink()) {
            std::fs::remove_file(path)?;
        }
        crate::cmd::write_atomic(path, render_resolv_conf().as_bytes())?;
        Ok(())
    }

    #[cfg(not(any(target_os = "macos", target_os = "windows", target_os = "linux")))]
    fn apply_os(&mut self, _tunnel: Option<&TunnelIface>) -> Result<()> {
        Err(vw_core::VwError::Unsupported("system DNS control"))
    }

    /// Restore whatever was saved. A no-op when nothing was changed.
    pub fn restore(&mut self) -> Result<()> {
        let Some(b) = self.backup.clone() else {
            return Ok(());
        };
        restore_os(&b)?;
        self.clear()
    }
}

#[cfg(target_os = "macos")]
fn restore_os(b: &DnsBackup) -> Result<()> {
    if let DnsBackup::MacOs { services } = b {
        for (svc, servers) in services {
            let a = macos_set_args(svc, servers);
            let a: Vec<&str> = a.iter().map(String::as_str).collect();
            // A service removed meanwhile cannot be restored; skip it.
            let out = crate::cmd::run("/usr/sbin/networksetup", &a, None)?;
            if !out.success {
                tracing::debug!("network service vanished before DNS restore");
            }
        }
    }
    Ok(())
}

#[cfg(target_os = "windows")]
fn restore_os(b: &DnsBackup) -> Result<()> {
    if let DnsBackup::Windows { iface } = b {
        let name = format!("name={iface}");
        for fam in ["ipv4", "ipv6"] {
            // The adapter may already be gone with the tunnel; that is fine.
            crate::cmd::run(
                "netsh",
                &[
                    "interface",
                    fam,
                    "delete",
                    "dnsservers",
                    &name,
                    "address=all",
                    "validate=no",
                ],
                None,
            )?;
        }
    }
    Ok(())
}

#[cfg(target_os = "linux")]
fn restore_os(b: &DnsBackup) -> Result<()> {
    match b {
        DnsBackup::Resolved { iface } => {
            let resolvectl =
                crate::cmd::resolve("resolvectl", &["/usr/bin/resolvectl", "/bin/resolvectl"]);
            crate::cmd::run(&resolvectl, &["revert", iface], None)?;
        }
        DnsBackup::ResolvConf { content, symlink } => {
            let path = Path::new("/etc/resolv.conf");
            if let Some(target) = symlink {
                let _ = std::fs::remove_file(path);
                std::os::unix::fs::symlink(target, path)?;
            } else if let Some(c) = content {
                crate::cmd::write_atomic(path, c.as_bytes())?;
            }
        }
        _ => {}
    }
    Ok(())
}

#[cfg(not(any(target_os = "macos", target_os = "windows", target_os = "linux")))]
fn restore_os(_b: &DnsBackup) -> Result<()> {
    Err(vw_core::VwError::Unsupported("system DNS control"))
}

/// Flush OS resolver caches (used by `voidwire panic`).
pub fn flush_caches() -> Result<()> {
    #[cfg(target_os = "macos")]
    {
        crate::cmd::run_ok("/usr/bin/dscacheutil", &["-flushcache"], None)?;
        crate::cmd::run_ok("/usr/bin/killall", &["-HUP", "mDNSResponder"], None)?;
        Ok(())
    }
    #[cfg(target_os = "windows")]
    {
        crate::cmd::run_ok("ipconfig", &["/flushdns"], None).map(drop)
    }
    #[cfg(target_os = "linux")]
    {
        let resolvectl =
            crate::cmd::resolve("resolvectl", &["/usr/bin/resolvectl", "/bin/resolvectl"]);
        // Without systemd-resolved there is no system cache to flush.
        crate::cmd::run(&resolvectl, &["flush-caches"], None).map(drop)
    }
    #[cfg(not(any(target_os = "macos", target_os = "windows", target_os = "linux")))]
    {
        Err(vw_core::VwError::Unsupported("DNS cache flush"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_networksetup() {
        let list = "An asterisk (*) denotes that a network service is disabled.\nUSB 10/100/1000 LAN\nWi-Fi\n*Thunderbolt Bridge\n";
        assert_eq!(
            parse_network_services(list),
            ["USB 10/100/1000 LAN", "Wi-Fi"]
        );
        assert!(parse_dns_servers("There aren't any DNS Servers set on Wi-Fi.\n").is_empty());
        assert_eq!(
            parse_dns_servers("192.168.1.1\n2001:db8::53\n"),
            ["192.168.1.1", "2001:db8::53"]
        );
        assert_eq!(
            macos_set_args("Wi-Fi", &[]).join(" "),
            "-setdnsservers Wi-Fi Empty"
        );
    }

    #[test]
    fn renders_vault_configs() {
        let r = render_resolv_conf();
        assert!(r.contains("nameserver 100.64.0.1") && r.contains("nameserver fd00:564f:4944::1"));
        let w = windows_set_args("vw0");
        assert_eq!(
            w[0].join(" "),
            "interface ipv4 set dnsservers name=vw0 source=static address=100.64.0.1 register=none validate=no"
        );
        assert!(w[1].join(" ").contains("address=fd00:564f:4944::1"));
    }

    #[test]
    fn backup_survives_restart_and_is_never_overwritten() {
        let dir = std::env::temp_dir().join(format!("vwfw-dns-{}", std::process::id()));
        let mut d = SystemDns::new(&dir);
        assert!(!d.is_applied());
        d.save(DnsBackup::Windows {
            iface: "vw0".into(),
        })
        .unwrap();
        d.save(DnsBackup::Windows {
            iface: "other".into(),
        })
        .unwrap();
        let reloaded = SystemDns::new(&dir);
        assert_eq!(
            reloaded.backup(),
            Some(&DnsBackup::Windows {
                iface: "vw0".into()
            })
        );
        d.clear().unwrap();
        assert!(!SystemDns::new(&dir).is_applied());
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
